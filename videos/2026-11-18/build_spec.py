def fmt_panel(p):
    if not p:
        return ""
    t = p.get("title", "")
    if p["kind"] in ("note", "tree"):
        body = " / ".join(p.get("lines") or p.get("items") or [])
    elif p["kind"] == "answer":
        body = p["big"] + "｜" + " / ".join(p["reasons"])
    else:
        body = " / ".join(f"{r['label']}：{r['text']}" for r in p["rows"])
    return f"［{t}］{body}"


